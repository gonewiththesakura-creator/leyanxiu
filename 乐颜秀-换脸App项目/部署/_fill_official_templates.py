# ---------- 基础工具 ----------

def set_text(p, text):
    """替换段落文本，保留首个 run 的格式"""
    runs = p.runs
    if runs:
        r = runs[0]
        for extra in runs[1:]:
            extra._element.getparent().remove(extra._element)
        r.text = text
    else:
        p.add_run(text)

def del_para(p):
    p._element.getparent().remove(p._element)

def find_para(doc, prefix, style_contains=None):
    for p in doc.paragraphs:
        t = p.text.strip()
        if t.startswith(prefix):
            if style_contains and style_contains not in p.style.name:
                continue
            return p
    raise RuntimeError(f"未找到段落: {prefix}")

def insert_after(anchor, text="", style=None):
    new_el = anchor._element.makeelement(qn("w:p"), {})
    anchor._element.addnext(new_el)
    np = Paragraph(new_el, anchor._parent)
    if style:
        np.style = np.part.document.styles[style]
    if text:
        np.add_run(text)
    return np

def insert_block(anchor, items):
    """items: [(style, text), ...]，依次插到 anchor 之后，返回最后一个段落"""
    cur = anchor
    for style, text in items:
        cur = insert_after(cur, text, style)
    return cur

def insert_image_after(anchor, img_path, width_cm, caption=None):
    ip = insert_after(anchor)
    ip.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = ip.add_run()
    run.add_picture(str(img_path), width=Cm(width_cm))
    last = ip
    if caption:
        cp = insert_after(ip, caption)
        cp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        last = cp
    return last

def set_cell(cell, text):
    """写入表格单元格（只保留一个段落）"""
    paras = cell.paragraphs
    set_text(paras[0], text)
    for extra in paras[1:]:
        if extra.text.strip():
            del_para(extra)

