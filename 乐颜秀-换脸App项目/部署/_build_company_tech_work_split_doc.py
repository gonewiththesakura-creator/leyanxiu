def add_labeled_para(doc, label, text, *, color=m.BLACK, after=3, keep=False):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after = Pt(after)
    p.paragraph_format.line_spacing = 1.18
    p.paragraph_format.keep_with_next = keep
    r1 = p.add_run(f"{label}：")
    m.set_run_font(r1, size=10, color=m.BLACK, bold=True)
    r2 = p.add_run(text)
    m.set_run_font(r2, size=10, color=color)
    return p


def add_task_block(doc, code, title, problem, action, counterpart, method, evidence):
    heading = m.add_heading(doc, f"{code} | {title}", 2)
    heading.paragraph_format.space_before = Pt(9)
    heading.paragraph_format.space_after = Pt(4)
    for run in heading.runs:
        m.set_run_font(run, size=12, color=m.DARK_BLUE, bold=True)
    add_labeled_para(doc, "问题与原因", problem, keep=True)
    add_labeled_para(doc, "具体怎么做", action)
    add_labeled_para(doc, "对方需配合", counterpart)
    method_color = m.CAUTION if "代办" in method or "专业" in method or "混合" in method else m.POSITIVE
    add_labeled_para(doc, "办理建议", method, color=method_color)
    add_labeled_para(doc, "完成证据", evidence, after=6)


