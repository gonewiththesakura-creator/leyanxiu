def set_font(run, name="宋体", size=12, bold=False, color=None):
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)
    run.font.size = Pt(size)
    run.font.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)

def para(doc, text="", size=12, bold=False, align=None, indent=True, name="宋体", space_after=6):
    p = doc.add_paragraph()
    r = p.add_run(text)
    set_font(r, name, size, bold)
    if align is not None:
        p.alignment = align
    if indent and align is None:
        p.paragraph_format.first_line_indent = Pt(size * 2)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.line_spacing = 1.4
    return p

def h1(doc, text):
    return para(doc, text, size=15, bold=True, indent=False, name="黑体", space_after=10)

def h2(doc, text):
    return para(doc, text, size=13, bold=True, indent=False, name="黑体", space_after=8)

