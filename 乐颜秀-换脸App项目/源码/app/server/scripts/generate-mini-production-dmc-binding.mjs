// Local SQL projection only. No database client, env loading or cloud operation.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { productionSchemaPlan, productionDatabase, productionAppId } from './generate-mini-production-schema.mjs';

const server = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const dmcBindingPath = path.join(server, 'deploy/mini-payment/production-binding-dmc-v2.sql');
const sessionGuard = `DATABASE() = '${productionDatabase}'
  AND @@SESSION.autocommit = 1
  AND @@SESSION.transaction_isolation IN ('READ-COMMITTED','REPEATABLE-READ','SERIALIZABLE')`;
const constraintGuard = `(SELECT COUNT(*) FROM information_schema.TABLE_CONSTRAINTS
    WHERE CONSTRAINT_SCHEMA = '${productionDatabase}' AND CONSTRAINT_TYPE = 'CHECK' AND ENFORCED = 'YES') = 36
  AND (SELECT COUNT(*) FROM information_schema.KEY_COLUMN_USAGE
    WHERE TABLE_SCHEMA = '${productionDatabase}' AND REFERENCED_TABLE_NAME IS NOT NULL) = 12
  AND (SELECT COUNT(*) FROM information_schema.KEY_COLUMN_USAGE
    WHERE TABLE_SCHEMA = '${productionDatabase}' AND REFERENCED_TABLE_SCHEMA = '${productionDatabase}' AND REFERENCED_TABLE_NAME IS NOT NULL) = 12`;

export function productionDmcBindingPlan() {
  const plan = productionSchemaPlan();
  const insert = plan.bind.find(sql => sql.startsWith('INSERT INTO '));
  if (!insert || !insert.includes(`WHERE DATABASE() = '${productionDatabase}'`)) throw new Error('PRODUCTION_DMC_BINDING_SOURCE_CHANGED');
  const statement = insert.replace(`WHERE DATABASE() = '${productionDatabase}'`, `WHERE ${sessionGuard}`) + `\n  AND ${constraintGuard}`;
  const before = plan.beforeBinding.at(-1).replace(/^SELECT \(/, `SELECT CONNECTION_ID() AS connection_id, DATABASE() AS selected_database,
  @@SESSION.autocommit AS autocommit, @@SESSION.transaction_isolation AS transaction_isolation,
  (${sessionGuard} AND ${constraintGuard} AND (`).replace(/\) AS ready_to_bind$/, ')) AS ready_to_bind');
  return { statement, preflight: before, postflight: plan.postflight, tables: plan.tables.map(table => table.name),
    businessTables: [...plan.businessTables], appId: productionAppId, database: productionDatabase };
}

export function renderProductionDmcBinding() {
  return `-- GENERATED by scripts/generate-mini-production-dmc-binding.mjs; local review only.
-- DMC fresh connection per statement: execute this ONE INSERT SELECT by itself.
-- Fixed ${productionDatabase}, ${productionAppId}, env=0; existing binding is never replaced.
-- Preconditions: approved 23-table fresh schema, all applications disconnected,
-- selected database exactly ${productionDatabase}, new session with autocommit=1,
-- session default READ-COMMITTED, REPEATABLE-READ or SERIALIZABLE; no transaction override.
-- REQUIRED external maintenance isolation: no app has privileges/configuration to use
-- this new database and no other admin/root writer or DDL is active until postflight.
-- Audit grants and deployment state BEFORE this statement; SQL cannot prove those facts.
-- NOT EXISTS is a statement-time check, NOT a lock against arbitrary concurrent writers.
-- This remains true for this subquery shape even under RR; never use on an active database.
-- This statement commits atomically on success; there is NO later manual COMMIT/ROLLBACK.
-- Require the INSERT's own affected-row result to be exactly 1.
-- A later SELECT ROW_COUNT() is meaningless in DMC's different connection.
-- Zero rows or any error/unknown reply: STOP. Do not blindly execute again.
-- From a fresh connection verify original vp_environment and full postflight instead.
-- No passwords/grants/users/credits/DDL/activation; never execute the old transaction stage here.
${productionDmcBindingPlan().statement};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.length === 2) console.log('NO_OP: use --check or --write; no database connected.');
  else if (process.argv.length === 3 && process.argv[2] === '--write') {
    const sql = renderProductionDmcBinding(); fs.writeFileSync(dmcBindingPath, sql, { flag: 'wx' });
    console.log(JSON.stringify({ path: dmcBindingPath, sha256: createHash('sha256').update(sql).digest('hex'), cloudSqlExecuted: false }));
  } else if (process.argv.length === 3 && process.argv[2] === '--check') {
    if (fs.readFileSync(dmcBindingPath, 'utf8') !== renderProductionDmcBinding()) throw new Error('PRODUCTION_DMC_BINDING_STALE');
    console.log('PASS DMC binding matches canonical source; no database connected.');
  } else throw new Error('PRODUCTION_DMC_ARGUMENTS_INVALID');
}
