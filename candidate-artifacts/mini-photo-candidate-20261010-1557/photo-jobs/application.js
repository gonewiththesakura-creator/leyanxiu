import { Hono } from 'hono';
import { isDeepStrictEqual } from 'node:util';
import { createPhotoJobContext } from './context.js';
import { createPhotoUploadRepository } from './upload-repository.js';
import { createPhotoUploadService, createPhotoUploadWorker } from './upload-service.js';
import { createPhotoUploadCleanupWorker } from './upload-cleanup.js';
import { createPhotoJobWorker } from './worker.js';
import { registerPhotoUploadRoutes, photoUploadProtocol } from './upload-routes.js';
import { registerPhotoJobRoutes, photoJobProtocol } from './routes.js';
import { registerNativePhotoRoutes } from './native-routes.js';

const fail = code => Object.assign(new Error(code), { code });
const id = (value, max = 80) => typeof value === 'string' && value.length <= max && /^[A-Za-z0-9][A-Za-z0-9_-]*$/.test(value);
const closedCatalog = () => ({ settings: { generationEnabled: false }, photoEffects: [],
  miniProgramCreation: { available: false, jobProtocol: photoJobProtocol, uploadProtocol: photoUploadProtocol, photoEffectIds: [] } });
const freeze = value => { if (value && typeof value === 'object') { Object.values(value).forEach(freeze); Object.freeze(value); } return value; };

/** Explicit native-photo composition. No environment reads, migrations, timers,
 * account creation, payment requests or automatic provider dispatch. The host
 * supplies the existing stable WeChat identity and canonical virtual ledger.
 * prepare() explicitly registers already-approved server effects; approval
 * references are operator evidence, never generated by this module.
 */
export function createPhotoApplication({ channel, ledger, authenticated, policy, approvedEffects = [],
  uploadStorage, moderator, runProvider, runProviderFactory, mediaUrl, cleanup,
  readiness = async () => ({ ready: false }), generationEnabled = false, storageTimeoutMs = 4000, now = Date.now } = {}) {
  if (channel !== 'wechat-mini-program') return Object.freeze({ active: false, managesSales: false,
    mount: () => false, prepare: async () => ({ prepared: false }), catalog: async () => closedCatalog(),
    runOnce: async () => null, drain: async () => ({ accepting: false, active: 0 }) });
  if (typeof authenticated !== 'function' || typeof readiness !== 'function' || typeof generationEnabled !== 'boolean'
    || !Array.isArray(approvedEffects) || approvedEffects.length > 100 || (runProvider && runProviderFactory)
    || (runProviderFactory && typeof runProviderFactory !== 'function') || (runProvider && typeof runProvider !== 'function')) {
    throw fail('PHOTO_APPLICATION_DEPENDENCIES_REQUIRED');
  }
  let config, effects;
  try { config = freeze(structuredClone(policy)); effects = freeze(structuredClone(approvedEffects)); }
  catch { throw fail('PHOTO_APPLICATION_APPROVAL_REQUIRED'); }
  if (effects.some(effect => !effect || effect.approved !== true || effect.enabled !== true || !id(effect.id) || !id(effect.version)
    || !id(effect.reviewReference, 128) || typeof effect.title !== 'string' || !effect.title.trim() || effect.title.length > 100
    || (effect.subtitle !== undefined && (typeof effect.subtitle !== 'string' || effect.subtitle.length > 300)))
    || new Set(effects.map(effect => effect.id)).size !== effects.length) throw fail('PHOTO_APPLICATION_APPROVAL_REQUIRED');
  const context = createPhotoJobContext({ ledger, policy: config, now });
  const database = context.database;
  const uploads = createPhotoUploadRepository({ database, policy: config, now });
  let prepared = false, preparing, mounted = false, accepting = true, running, draining;
  const activeHttp = new Set(), activeUploadPorts = new Set();
  const track = (target, name) => (...args) => {
    const operation = Promise.resolve().then(() => target[name](...args));
    activeUploadPorts.add(operation); operation.finally(() => activeUploadPorts.delete(operation)).catch(() => {}); return operation;
  };
  if (!['put', 'read'].every(name => typeof uploadStorage?.[name] === 'function')) throw fail('PHOTO_APPLICATION_STORAGE_REQUIRED');
  const storage = { put: track(uploadStorage, 'put'), read: track(uploadStorage, 'read') };
  // Include confirmStored after a bounded HTTP request has already returned;
  // draining the object PUT alone would omit its late SQL receipt write.
  const trackedUploads = Object.fromEntries(Object.keys(uploads).map(name => [name, track(uploads, name)]));
  const service = createPhotoUploadService({ repository: trackedUploads, storage, timeoutMs: storageTimeoutMs });
  const uploadWorker = createPhotoUploadWorker({ repository: trackedUploads, storage, moderator, timeoutMs: storageTimeoutMs });
  // The factory can close over the exact context instead of introducing a
  // second context/ledger or a mutable late-binding provider setter.
  const supplied = runProviderFactory ? runProviderFactory({ context }) : runProvider;
  const lifecycleNames = ['runProvider', 'prepare', 'readiness', 'runCleanupOnce', 'drain'];
  const generation = supplied && typeof supplied === 'object' ? supplied : null;
  if (generation && (generation.database !== database || lifecycleNames.some(name => typeof generation[name] !== 'function'))) {
    throw fail('PHOTO_APPLICATION_GENERATION_LIFECYCLE_REQUIRED');
  }
  // Snapshot the explicit lifecycle. It must belong to this canonical database
  // and include output cleanup; an upload-only cleanup is not sufficient.
  const lifecycle = generation ? Object.fromEntries(lifecycleNames.map(name => [name, generation[name].bind(generation)])) : null;
  const provider = lifecycle ? lifecycle.runProvider : supplied;
  if (provider !== undefined && typeof provider !== 'function') throw fail('PHOTO_APPLICATION_PROVIDER_REQUIRED');
  if (generationEnabled && typeof provider !== 'function') throw fail('PHOTO_APPLICATION_PROVIDER_REQUIRED');
  if (generationEnabled && !lifecycle) throw fail('PHOTO_APPLICATION_GENERATION_LIFECYCLE_REQUIRED');
  const jobWorker = createPhotoJobWorker({ repository: context.repository, runProvider: provider || (async () => { throw fail('PHOTO_APPLICATION_PROVIDER_REQUIRED'); }) });
  const cleanupWorker = cleanup ? createPhotoUploadCleanupWorker({ repository: uploads,
    sourceStorage: cleanup.sourceStorage, moderationStorage: cleanup.moderationStorage, policy: cleanup.policy }) : null;
  const approvedCurrent = async () => database.transaction(async q => {
    const rows = await q('SELECT effect_id,version,provider,model,purpose,parameters,review_reference FROM mini_photo_effects WHERE enabled = 1');
    return effects.every(effect => {
      const selected = rows.filter(row => row.effect_id === effect.id);
      if (selected.length !== 1) return false;
      const row = selected[0];
      return row.version === effect.version && row.provider === effect.provider && row.model === effect.model
        && row.purpose === effect.purpose && row.review_reference === effect.reviewReference
        && isDeepStrictEqual(JSON.parse(row.parameters), effect.parameters ?? {});
    });
  });
  const ready = async userId => {
    if (!prepared || !mounted || !accepting || !generationEnabled || !cleanupWorker || !lifecycle || !effects.length) return { ready: false, photoEffectIds: [] };
    try {
      if ((await readiness(userId))?.ready !== true || (await lifecycle.readiness(userId))?.ready !== true
        || !await approvedCurrent() || !accepting) return { ready: false, photoEffectIds: [] };
      return { ready: true, photoEffectIds: effects.map(effect => effect.id) };
    } catch { return { ready: false, photoEffectIds: [] }; }
  };
  const catalog = async () => {
    const state = await ready();
    return { settings: { generationEnabled: state.ready },
      miniProgramCreation: { available: state.ready, jobProtocol: photoJobProtocol, uploadProtocol: photoUploadProtocol,
        photoEffectIds: state.ready ? [...state.photoEffectIds] : [] },
      photoEffects: effects.map(effect => ({ id: effect.id, title: effect.title,
        subtitle: effect.subtitle || '', enabled: true })) };
  };
  const router = new Hono();
  router.use('*', async (_c, next) => {
    let done; const operation = new Promise(resolve => { done = resolve; }); activeHttp.add(operation);
    try { await next(); } finally { activeHttp.delete(operation); done(); }
  });
  registerNativePhotoRoutes(router, { authenticated, context, ready, mediaUrl, now });
  registerPhotoUploadRoutes(router, { service, authenticated, readiness: ready });
  registerPhotoJobRoutes(router, { context, authenticated, readiness: ready });
  router.get('/api/catalog', async c => { c.header('Cache-Control', 'no-store'); return c.json({ code: 0, data: await catalog() }); });
  // These exact old write entrances are deliberately intercepted before the
  // legacy application's routes. Existing payment/query/refund routes remain
  // the host's responsibility and are neither enabled nor reimplemented here.
  for (const path of ['/api/photo/effect', '/api/photo/restore', '/api/photo/fusion', '/api/photo/idphoto', '/api/photo/age',
    '/api/photo/anime', '/api/photo/photobg', '/api/fusion', '/api/video/matting', '/api/upload', '/api/upload/video',
    '/api/moderation/check', '/api/llm/chat', '/api/play/analyze']) {
    router.post(path, c => c.json({ code: 'PHOTO_NATIVE_ASYNC_REQUIRED', message: '请从小程序创作页提交并查询原图片任务。' }, 409));
  }
  router.delete('/api/account', c => c.json({ code: 'PHOTO_ACCOUNT_CANCELLATION_REVIEW_REQUIRED',
    message: '请通过客户支持提交注销申请；当前请求未注销账号或清除权益。' }, 409));
  return {
    active: true, managesSales: false, context, uploads,
    mount(app) {
      if (mounted || !accepting || typeof app?.route !== 'function') throw fail('PHOTO_APPLICATION_MOUNT_INVALID');
      app.route('/', router); mounted = true; return true;
    },
    prepare() {
      if (!accepting) return Promise.reject(fail('PHOTO_APPLICATION_DRAINING'));
      if (prepared) return Promise.resolve({ prepared: true });
      if (!preparing) preparing = (async () => {
        // SELECT only: migrations must already have been explicitly applied to
        // this same ledger database. Missing columns/tables cannot enable HTTP.
        await database.transaction(async q => {
          await q('SELECT user_id,app_id,openid FROM vp_accounts LIMIT 0');
          await q('SELECT user_id,enabled,consent_epoch,basic_version,face_version,subject_authorization,updated_at FROM mini_photo_accounts LIMIT 0');
          await q('SELECT id,user_id,kind,state,storage_key,sha256,byte_length,content_type,consent_epoch,job_id,moderation_reference,label_version,expires_at,created_at FROM mini_photo_assets LIMIT 0');
          await q('SELECT job_id,asset_id,user_id,created_at FROM mini_photo_works LIMIT 0');
          await q('SELECT id,user_id,idem,state,spec,claim_token,attempt,output_asset_id FROM mini_photo_jobs LIMIT 0');
          await q('SELECT id,user_id,idem,state,consent_epoch,moderation_cleanup_reference,moderation_cleanup_extension FROM mini_photo_uploads LIMIT 0');
          if (cleanupWorker) await q('SELECT upload_id,kind,storage_key,state,operation_token,next_at FROM mini_photo_upload_cleanup LIMIT 0');
          if (lifecycle) {
            await q('SELECT job_id,user_id,spec_hash,policy,asset_id,output_key,marked_sha256,marked_length,marked_type,provider_receipt,review_receipt,moderation_reference,moderation_extension,moderation_cleanup_pending,output_cleanup_pending,registered,expires_at,created_at,updated_at FROM mini_photo_generation LIMIT 0');
            await q('SELECT job_id,step,state,token,attempts,started_at,updated_at FROM mini_photo_generation_operations LIMIT 0');
            await q('SELECT job_id,kind,storage_key,state,attempts,operation_token,delete_status,observation,next_at,checked_at,absent_observations,created_at,updated_at FROM mini_photo_generation_cleanup LIMIT 0');
          }
        });
        if (lifecycle && (await lifecycle.prepare())?.prepared !== true) throw fail('PHOTO_APPLICATION_GENERATION_NOT_PREPARED');
        for (const effect of effects) await context.putEffect(effect);
        if (!await approvedCurrent()) throw fail('PHOTO_APPLICATION_EFFECT_DRIFT');
        prepared = true; return { prepared: true };
      })().finally(() => { preparing = undefined; });
      return preparing;
    },
    catalog,
    runOnce({ process = false, cleanup: clean = false } = {}) {
      if (!accepting || !prepared || !mounted || (!process && !clean)) return Promise.resolve(null);
      if (running) return running;
      running = (async () => {
        const result = {};
        if (process === true && (await ready()).ready) {
          if (accepting) result.upload = await uploadWorker.runOnce();
          if (accepting && (await ready()).ready) result.job = await jobWorker.runOnce();
        }
        if (clean === true && accepting && cleanupWorker) result.cleanup = await cleanupWorker.runOnce();
        if (clean === true && accepting && lifecycle) result.generationCleanup = await lifecycle.runCleanupOnce();
        return result;
      })();
      running.finally(() => { running = undefined; }).catch(() => {}); return running;
    },
    drain() {
      if (draining) return draining;
      accepting = false;
      // The host first stops accepting HTTP. Workers stop claims immediately;
      // any admitted work and late upload PUT continuation remain tracked.
      const workers = [uploadWorker.drain(), jobWorker.drain(), ...(cleanupWorker ? [cleanupWorker.drain()] : [])];
      draining = (async () => {
        await Promise.allSettled([preparing, running, ...workers, ...activeHttp].filter(Boolean));
        while (activeUploadPorts.size) await Promise.allSettled([...activeUploadPorts]);
        // Admitted generation completes before its adapters are drained. This
        // lets a provider receipt/final output settle without starting new work.
        if (lifecycle) await lifecycle.drain();
        return { accepting: false, active: activeHttp.size + activeUploadPorts.size, databaseClosed: false };
      })();
      return draining;
    },
  };
}
